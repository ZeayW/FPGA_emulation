"""Controlled communication probes for bandwidth, TDM, latency, and cost."""

from __future__ import annotations

import hashlib
import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Sequence

from .errors import ValidationError
from .io import write_json
from .ppro_blackbox_ppro_adapter import PPRO_2026_REPORT_PROFILE
from .ppro_blackbox_runner import (
    MOCK_REPORT_PROFILE,
    RUN_SPEC_SCHEMA,
    SUPPORTED_REPORT_PROFILES,
    validate_run_spec,
)


COMMUNICATION_KINDS = {"payload_capacity", "latency", "transport_cost"}
_GENERATOR_ID = "ppro-blackbox-communication-probe-v5"
_EXPECTED_REPORTS = [
    "partition_summary",
    "resource_summary",
    "route_summary",
    "route_timing",
    "net_tdm",
]


@dataclass(frozen=True)
class CommunicationProbeBundle:
    root: Path
    rtl_path: Path
    filelist_path: Path
    parameters_path: Path
    constraints_path: Path
    run_spec_path: Path
    run_spec: Dict[str, Any]


def _positive_unique(values: Sequence[int], name: str) -> tuple[int, ...]:
    normalized = tuple(values)
    if (
        not normalized
        or any(isinstance(value, bool) or not isinstance(value, int) or value <= 0 for value in normalized)
        or len(normalized) != len(set(normalized))
    ):
        raise ValidationError(f"communication matrix {name} must be unique positive integers")
    return normalized


def _canonical(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _sha256(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _johnson_update(name: str, width: int) -> str:
    # An inverted feedback shift register gives every bit a nonconstant,
    # phase-distinct waveform without a width-dependent arithmetic carry path.
    return f"~{name}" if width == 1 else f"{{{name}[{width - 2}:0], ~{name}[{width - 1}]}}"


def _communication_rtl(width: int, reverse_width: int, flow_count: int, fanout: int) -> str:
    forward_bits = width * flow_count
    reverse_bits = reverse_width * flow_count
    return_bits = reverse_bits * fanout
    keep = '(* keep = "true", dont_touch = "yes", shreg_extract = "no" *)'
    source_ports = [
        "input wire clk", "input wire reset_n",
        f"output reg [{forward_bits - 1}:0] payload",
    ]
    source_return = ""
    sink_return_port = ""
    sink_return = ""
    source_return_connection = ""
    return_wires: list[str] = []
    digest_count = fanout + int(reverse_bits > 0)
    if reverse_bits:
        source_ports += [f"input wire [{return_bits - 1}:0] return_payload", "output wire digest"]
        source_return = f"""
    {keep}
    reg [{return_bits - 1}:0] received_return;
    always @(posedge clk) begin
        if (!reset_n) received_return <= {{{return_bits}{{1'b0}}}};
        else received_return <= return_payload;
    end
    assign digest = ^received_return;
"""
        sink_return_port = f",\n    output reg [{reverse_bits - 1}:0] return_payload"
        sink_return = f"""
    always @(posedge clk) begin
        if (!reset_n) return_payload <= {{{reverse_bits}{{1'b1}}}};
        else return_payload <= {_johnson_update("return_payload", reverse_bits)};
    end
"""
        return_wires = [
            f"    wire [{reverse_bits - 1}:0] return_payload_{index};"
            for index in range(fanout)
        ]
        concatenated = ", ".join(f"return_payload_{index}" for index in reversed(range(fanout)))
        source_return_connection = f", .return_payload({{{concatenated}}}), .digest(digest[{fanout}])"
    consumer_instances = []
    for index in range(fanout):
        reverse_connection = f", .return_payload(return_payload_{index})" if reverse_bits else ""
        consumer_instances.append(
            f"    (* keep_hierarchy = \"yes\", dont_touch = \"yes\" *)\n"
            f"    calibration_sink P{index + 1} (.clk(clk), .reset_n(reset_n), "
            f".payload(payload), .digest(digest[{index}]){reverse_connection});"
        )
    return f"""// Generated by {_GENERATOR_ID}; logical endpoints are mapped at runtime.
// Forward and reverse widths are independent. Clock/reset/digest are not data load.
(* keep_hierarchy = "yes" *)
module calibration_source (
    {(',' + chr(10) + '    ').join(source_ports)}
);
    always @(posedge clk) begin
        if (!reset_n) payload <= {{{forward_bits}{{1'b0}}}};
        else payload <= {_johnson_update("payload", forward_bits)};
    end
{source_return}endmodule

(* keep_hierarchy = "yes" *)
module calibration_sink (
    input wire clk,
    input wire reset_n,
    input wire [{forward_bits - 1}:0] payload,
    output wire digest{sink_return_port}
);
    {keep}
    reg [{forward_bits - 1}:0] received_payload;
    always @(posedge clk) begin
        if (!reset_n) received_payload <= {{{forward_bits}{{1'b0}}}};
        else received_payload <= payload;
    end
    assign digest = ^received_payload;
{sink_return}endmodule

module ppro_blackbox_communication_probe (
    input wire clk,
    input wire reset_n,
    output wire [{digest_count - 1}:0] digest
);
    wire [{forward_bits - 1}:0] payload;
{chr(10).join(return_wires)}
    (* keep_hierarchy = "yes", dont_touch = "yes" *)
    calibration_source P0 (.clk(clk), .reset_n(reset_n), .payload(payload){source_return_connection});
{chr(10).join(consumer_instances)}
endmodule
"""


def generate_communication_probe_bundle(
    output_dir: Path,
    *,
    kind: str,
    fpga_count: int,
    source_index: int,
    sink_indices: Sequence[int],
    width: int,
    flow_count: int,
    reverse_width: int = 0,
    clock_period_ns: float = 10.0,
    local_baseline: bool,
    forced_tdm_ratio: int,
    repeat: int,
    role: str,
    campaign_id: str,
    public_prior_id: str,
    configuration_id: str,
    tool_release: str,
    runner_revision: str,
    seed: int,
    adapter_profile: str = PPRO_2026_REPORT_PROFILE,
    pairing_token: int | None = None,
) -> CommunicationProbeBundle:
    if kind not in COMMUNICATION_KINDS:
        raise ValidationError(f"communication kind must be one of {sorted(COMMUNICATION_KINDS)}")
    if adapter_profile not in SUPPORTED_REPORT_PROFILES:
        raise ValidationError("communication adapter profile is unsupported")
    generator_id = _GENERATOR_ID + ("-mock" if adapter_profile == MOCK_REPORT_PROFILE else "")
    if adapter_profile != MOCK_REPORT_PROFILE and forced_tdm_ratio:
        raise ValidationError(
            "real PPro forced-TDM probes require a documented provider constraint syntax"
        )
    for name, value, minimum in (
        ("fpga_count", fpga_count, 2),
        ("width", width, 1),
        ("flow_count", flow_count, 1),
        ("reverse_width", reverse_width, 0),
        ("forced_tdm_ratio", forced_tdm_ratio, 0),
        ("repeat", repeat, 0),
        ("seed", seed, 0),
    ):
        if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
            raise ValidationError(f"communication {name} must be an integer >= {minimum}")
    if type(local_baseline) is not bool:
        raise ValidationError("communication baseline flag must be boolean")
    if (
        isinstance(clock_period_ns, bool)
        or not isinstance(clock_period_ns, (int, float))
        or not math.isfinite(clock_period_ns)
        or clock_period_ns <= 0
    ):
        raise ValidationError("communication clock_period_ns must be finite and positive")
    sinks = tuple(sink_indices)
    if not sinks:
        raise ValidationError("communication sink indices must be non-empty")
    if not local_baseline and len(sinks) != len(set(sinks)):
        raise ValidationError("cross-FPGA communication sink indices must be unique")
    if not 0 <= source_index < fpga_count or any(sink < 0 or sink >= fpga_count for sink in sinks):
        raise ValidationError("communication endpoints must select distinct configured FPGAs")
    if local_baseline:
        if kind != "transport_cost" or any(sink != source_index for sink in sinks):
            raise ValidationError("local baseline requires transport_cost endpoints on one FPGA")
    elif any(sink == source_index for sink in sinks):
        raise ValidationError("communication endpoints must select distinct configured FPGAs")
    if pairing_token is None:
        pairing_token = int(
            _sha256(
                _canonical(
                    {
                        "reverse_width": reverse_width,
                        "clock_period_ns": float(clock_period_ns),
                        "campaign_id": campaign_id,
                        "flow_count": flow_count,
                        "kind": kind,
                        "repeat": repeat,
                        "role": role,
                        "sink_indices": list(sinks),
                        "source_index": source_index,
                        "width": width,
                    }
                )
            )[:13],
            16,
        )
    if isinstance(pairing_token, bool) or not isinstance(pairing_token, int) or pairing_token < 0:
        raise ValidationError("communication pairing_token must be a nonnegative integer")

    root = output_dir.resolve()
    root.mkdir(parents=True, exist_ok=True)
    rtl_path = root / "communication_probe.v"
    filelist_path = root / "sources.f"
    parameters_path = root / "parameters.json"
    constraints_path = root / "documented_constraints.json"
    run_spec_path = root / "run-spec.json"
    rtl = _communication_rtl(width, reverse_width, flow_count, len(sinks))
    rtl_path.write_text(rtl, encoding="utf-8")
    filelist_path.write_text("communication_probe.v\n", encoding="utf-8")
    parameters = {
        "reverse_width": reverse_width,
        "clock_period_ns": float(clock_period_ns),
        "flow_count": flow_count,
        "fpga_count": fpga_count,
        "generator": generator_id,
        "local_baseline": local_baseline,
        "sink_indices": list(sinks),
        "source_index": source_index,
        "width": width,
    }
    actions = ["partition_constraint"]
    if forced_tdm_ratio:
        actions.append("tdm_ratio_constraint")
    constraints = {
        "assignments": [
            {"partition": "P0", "target": f"F{source_index}"},
            *[
                {"partition": f"P{index + 1}", "target": f"F{sink}"}
                for index, sink in enumerate(sinks)
            ],
        ],
        "control_mode": "fixed_assignment",
        "documented_actions": sorted(actions),
        "forced_tdm_ratio": forced_tdm_ratio,
        "seed": seed,
        "timing_clocks": [{"port": "clk", "period_ns": float(clock_period_ns)}],
    }
    write_json(parameters_path, parameters, compact=True)
    write_json(constraints_path, constraints, compact=True)
    period_id = str(float(clock_period_ns)).replace(".", "p").replace("+", "p").replace("-", "m")
    case_id = (
        f"{kind}-f{source_index}-s{'-'.join(str(value) for value in sinks)}"
        f"-w{width}-rw{reverse_width}-n{flow_count}-p{period_id}-t{forced_tdm_ratio}-r{repeat}"
    )
    spec = {
        "schema": RUN_SPEC_SCHEMA,
        "identity": {
            "id": f"{campaign_id}.{case_id}",
            "campaign_id": campaign_id,
            "case_id": case_id,
            "role": role,
            "public_prior_id": public_prior_id,
            "configuration_id": configuration_id,
        },
        "tool": {
            "name": "PPro",
            "release": tool_release,
            "runner_revision": runner_revision,
        },
        "workload": {
            "generator_id": generator_id,
            "generator_revision": hashlib.sha256(generator_id.encode("utf-8")).hexdigest(),
            "rtl_sha256": _sha256(rtl.encode("utf-8")),
            "parameters_sha256": _sha256(_canonical(parameters)),
            "top_module": "ppro_blackbox_communication_probe",
            "design_metrics": {
                "bidirectional": int(reverse_width > 0),
                "reverse_width_bits": reverse_width,
                "forward_data_bits": width * flow_count,
                "reverse_data_bits_per_sink": reverse_width * flow_count,
                "clock_period_ns": float(clock_period_ns),
                "endpoint_count": 1 + len(sinks),
                "fanout": len(sinks),
                "flow_count": flow_count,
                "forced_tdm_ratio": forced_tdm_ratio,
                "local_baseline": int(local_baseline),
                "pairing_token": pairing_token,
                "probe_width_bits": width,
                "repeat_index": repeat,
                "sink_fpga_index": sinks[0],
                "source_fpga_index": source_index,
            },
        },
        "experiment": {
            "kind": kind,
            "control_mode": "fixed_assignment",
            "documented_actions": sorted(actions),
            "constraints_sha256": _sha256(_canonical(constraints)),
        },
        "execution": {"seed": seed},
        "adapter": {
            "profile": adapter_profile,
            "expected_reports": (
                _EXPECTED_REPORTS
                if adapter_profile == PPRO_2026_REPORT_PROFILE
                else ["partition_summary", "resource_summary", "route_summary", "system_timing"]
                if kind == "latency"
                else ["partition_summary", "resource_summary", "route_summary"]
                if kind == "payload_capacity"
                else ["partition_summary", "resource_summary"]
            ),
        },
    }
    normalized = validate_run_spec(spec)
    write_json(run_spec_path, normalized, compact=True)
    return CommunicationProbeBundle(
        root=root,
        rtl_path=rtl_path,
        filelist_path=filelist_path,
        parameters_path=parameters_path,
        constraints_path=constraints_path,
        run_spec_path=run_spec_path,
        run_spec=normalized,
    )


def generate_communication_matrix(
    output_dir: Path,
    *,
    kind: str,
    fpga_count: int,
    source_index: int,
    sink_indices: Sequence[int],
    fit_widths: Sequence[int],
    holdout_widths: Sequence[int],
    flow_counts: Sequence[int],
    reverse_width: int = 0,
    clock_period_ns: float = 10.0,
    repeats: int,
    campaign_id: str,
    public_prior_id: str,
    configuration_id: str,
    tool_release: str,
    runner_revision: str,
    seed_base: int,
    adapter_profile: str = PPRO_2026_REPORT_PROFILE,
) -> list[CommunicationProbeBundle]:
    """Generate a bounded fit/holdout matrix with paired transport baselines."""

    if (
        isinstance(clock_period_ns, bool)
        or not isinstance(clock_period_ns, (int, float))
        or not math.isfinite(clock_period_ns)
        or clock_period_ns <= 0
    ):
        raise ValidationError("communication clock_period_ns must be finite and positive")
    fit = _positive_unique(fit_widths, "fit_widths")
    holdout = _positive_unique(holdout_widths, "holdout_widths")
    flows = _positive_unique(flow_counts, "flow_counts")
    if set(fit) & set(holdout):
        raise ValidationError("communication fit and holdout widths must be disjoint")
    if isinstance(repeats, bool) or not isinstance(repeats, int) or repeats < 2:
        raise ValidationError("communication matrix repeats must be an integer >= 2")
    if isinstance(seed_base, bool) or not isinstance(seed_base, int) or seed_base < 0:
        raise ValidationError("communication matrix seed_base must be a nonnegative integer")
    sinks = tuple(sink_indices)
    bundles: list[CommunicationProbeBundle] = []
    for role, widths in (("fit", fit), ("holdout", holdout)):
        for width in widths:
            for flow_count in flows:
                for repeat in range(repeats):
                    pairing_token = int(
                        _sha256(
                            _canonical(
                                {
                                    "reverse_width": reverse_width,
                                    "clock_period_ns": float(clock_period_ns),
                                    "campaign_id": campaign_id,
                                    "flow_count": flow_count,
                                    "kind": kind,
                                    "repeat": repeat,
                                    "role": role,
                                    "sink_indices": list(sinks),
                                    "source_index": source_index,
                                    "width": width,
                                }
                            )
                        )[:13],
                        16,
                    )
                    common = {
                        "kind": kind,
                        "fpga_count": fpga_count,
                        "source_index": source_index,
                        "width": width,
                        "flow_count": flow_count,
                        "reverse_width": reverse_width,
                        "clock_period_ns": float(clock_period_ns),
                        "forced_tdm_ratio": 0,
                        "repeat": repeat,
                        "role": role,
                        "campaign_id": campaign_id,
                        "public_prior_id": public_prior_id,
                        "configuration_id": configuration_id,
                        "tool_release": tool_release,
                        "runner_revision": runner_revision,
                        "seed": seed_base + repeat,
                        "adapter_profile": adapter_profile,
                        "pairing_token": pairing_token,
                    }
                    point = f"{role}/w{width}/rw{reverse_width}/n{flow_count}/r{repeat}"
                    if kind == "transport_cost":
                        bundles.append(
                            generate_communication_probe_bundle(
                                output_dir / point / "local",
                                sink_indices=[source_index] * len(sinks),
                                local_baseline=True,
                                **common,
                            )
                        )
                    bundles.append(
                        generate_communication_probe_bundle(
                            output_dir / point / "cross",
                            sink_indices=sinks,
                            local_baseline=False,
                            **common,
                        )
                    )
    return bundles
